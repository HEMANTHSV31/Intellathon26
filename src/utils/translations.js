// Case-insensitive lookup helper
const lowerLookup = new Map()
for (const [k, v] of Object.entries(translations)) {
  lowerLookup.set(k.toLowerCase().trim(), v)
}

export function translateText(text, targetLang = 'en') {
  if (!text || targetLang === 'en') return text
  const trimmed = text.trim()
  if (translations[trimmed]) return translations[trimmed]
  const lower = trimmed.toLowerCase()
  if (lowerLookup.has(lower)) return lowerLookup.get(lower)
  return text
}
