// Backward compatibility: default translations object points to Tamil
export const translations = translationsByLang.ta

// Case-insensitive lookup map per language
const lowerLookupByLang = new Map()
for (const [lang, dict] of Object.entries(translationsByLang)) {
  const map = new Map()
  for (const [k, v] of Object.entries(dict)) {
    map.set(k.toLowerCase().trim(), v)
  }
  lowerLookupByLang.set(lang, map)
}

export function getTranslationsForLang(lang = 'ta') {
  return translationsByLang[lang] || translationsByLang.ta || {}
}

export function translateText(text, targetLang = 'en') {
  if (!text || targetLang === 'en') return text
  const dict = translationsByLang[targetLang]
  if (!dict) return text
  const trimmed = text.trim()
  if (dict[trimmed]) return dict[trimmed]

  const lowerMap = lowerLookupByLang.get(targetLang)
  if (lowerMap) {
    const lower = trimmed.toLowerCase()
    if (lowerMap.has(lower)) return lowerMap.get(lower)
  }

  return text
}
